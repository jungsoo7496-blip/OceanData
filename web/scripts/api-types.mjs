// 계약(contracts/openapi.yaml) → TypeScript 타입 (09번 작업 16, 03번 요구사항 2.3). 생성 파일은 손으로 고치지 않는다.
// node scripts/api-types.mjs          생성
// node scripts/api-types.mjs --check  생성 결과가 저장소 파일과 같은지 (CI)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const SPEC = new URL('../../contracts/openapi.yaml', import.meta.url)
const OUT = fileURLToPath(new URL('../src/contract/api.gen.ts', import.meta.url))
const HEADER = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n'

const text = HEADER + astToString(await openapiTS(SPEC))
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') } catch { /* 없음 */ }
  if (current !== text) {
    console.error('웹 계약 타입이 계약과 다릅니다. npm run gen:api 를 실행하세요')
    process.exit(1)
  }
  console.log('웹 계약 타입 일치')
} else {
  writeFileSync(OUT, text)
  console.log(`생성: ${OUT}`)
}
